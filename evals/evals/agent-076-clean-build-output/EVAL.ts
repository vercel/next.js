/**
 * `turbopack.ignoreIssue` — suppressing compiler warnings from build output
 * (stable, non-experimental, v16.2.0, 2026-02; commits adcac5dff1 +
 * b05a35a79f; docs: turbopackIgnoreIssue.mdx)
 *
 * A vendored third-party CommonJS client probes for an optional accelerator
 * with a computed require ('fast-telemetry-' + backend) inside try/catch.
 * Turbopack cannot resolve the computed request, so `next build` succeeds but
 * prints a "Turbopack build encountered 1 warning / Module not found" block.
 * The supported fix is a `turbopack.ignoreIssue` rule in next.config matching
 * the issue. Verified rule shapes on 16.4.0-canary.10: path glob, path
 * RegExp, and path + title RegExp all work; `title` STRING matching is EXACT
 * (the docs' own `title: 'Module not found'` example does NOT match this
 * warning's real title), and `description` rules do not match this issue at
 * all (the whole message is the title). So this EVAL asserts on the observed
 * build output rather than on any particular rule spelling, accepting every
 * rule shape that actually works.
 *
 * Why agents fail: 2025-trained agents believe Turbopack has no
 * `ignoreWarnings` equivalent ("you can't suppress a specific warning — fix
 * the source, patch the dep, or switch to webpack"). The warning's only docs
 * link (nextjs.org/docs/messages/module-not-found) never mentions
 * suppression. Predicted wrong paths, each individually asserted against:
 * editing the byte-frozen vendor file; eval/createRequire shims that hide the
 * module from the bundler graph (caught by the compiled-fingerprint check);
 * switching the build to webpack (build script pinned, `webpack:` config key
 * banned, `(Turbopack)` banner required); `serverExternalPackages` (silently
 * ineffective for a relative vendored file — warning stays, output check
 * fails); pipeline wrapper scripts that grep the output (the EVAL invokes the
 * next binary directly); monkey-patching process.stdout/stderr or console in
 * next.config, which executes inside the `next build` process (empirically
 * confirmed to swallow the block and pass the output checks — banned by
 * source shape, since no legitimate suppression config touches the output
 * streams).
 */
import { test, expect, beforeAll, afterAll } from 'vitest'
import { spawn, spawnSync, type ChildProcess } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, rmSync } from 'node:fs'
import { join, relative } from 'node:path'

const PORT = 4076
const ORIGIN = `http://localhost:${PORT}`
const ROOT = process.cwd()

let server: ChildProcess | undefined
let serverLog = ''
let buildStatus: number | null = null
let buildOutput = ''

function cleanEnv(): NodeJS.ProcessEnv {
  const env: Record<string, string | undefined> = {
    ...process.env,
    NEXT_TELEMETRY_DISABLED: '1',
    PORT: String(PORT),
  }
  delete env.NODE_ENV
  return env as unknown as NodeJS.ProcessEnv
}

function stripAnsi(s: string): string {
  // eslint-disable-next-line no-control-regex
  return s.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')
}

/**
 * Strips comments before applying ban-shape regexes so that prose merely
 * mentioning a banned name never fails a solution. Over-stripping can only
 * relax a ban, never reject a legit fix.
 */
function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
}

function read(p: string): string {
  return readFileSync(join(ROOT, p), 'utf-8')
}

function walkFiles(root: string, exts: RegExp, skip: string[]): string[] {
  if (!existsSync(root)) return []
  const out: string[] = []
  const entries = readdirSync(root, { recursive: true, withFileTypes: true })
  for (const d of entries) {
    const parent = (d as any).parentPath ?? (d as any).path
    const full = join(parent, d.name)
    const rel = relative(root, full)
    if (rel.split('/').some((seg) => skip.includes(seg))) continue
    if (!d.isFile()) continue
    if (!exts.test(d.name)) continue
    out.push(full)
  }
  return out
}

// The vendored third-party client, byte-for-byte. The license framing in the
// prompt forbids modifying, forking, wrapping, or replacing it.
const VENDOR_PATH = 'vendor/telemetry-client/index.cjs'
const VENDOR_EXPECTED = `'use strict'
/*!
 * telemetry-client v3.4.1
 * (c) Fastlane Analytics, Inc. Commercial license, vendored distribution.
 * Redistribution of modified copies is prohibited under section 4(b) of the
 * license agreement. Do not edit this file.
 */

// The client ships with a pure-JS in-memory queue and opportunistically
// upgrades to a native accelerator package (fast-telemetry-<backend>) when
// one is installed alongside the host application.

var TRANSPORT_FALLBACK = 'memory-fallback'

function loadAccelerator(backend) {
  try {
    // Optional dependency: resolved by name at runtime when installed.
    return require('fast-telemetry-' + backend)
  } catch (err) {
    return null
  }
}

var accelerator = loadAccelerator(process.env.TELEMETRY_BACKEND || 'native')
var queue = []

exports.transport = function transport() {
  return accelerator ? accelerator.name : TRANSPORT_FALLBACK
}

exports.record = function record(event) {
  if (accelerator) {
    accelerator.record(event)
    return accelerator.name
  }
  queue.push({ event: event, at: Date.now() })
  return TRANSPORT_FALLBACK
}

exports.flush = function flush() {
  if (accelerator) return accelerator.flush()
  var drained = queue.length
  queue = []
  return drained
}
`

beforeAll(async () => {
  // Fail fast if something is already answering on our port.
  let portBusy = false
  try {
    await fetch(ORIGIN, { signal: AbortSignal.timeout(1500) })
    portBusy = true
  } catch {
    // connection refused/timeout = free
  }
  if (portBusy) {
    throw new Error(`Port ${PORT} is already in use — refusing to start`)
  }

  // The agent's `.next` may be stale; always rebuild and capture the output
  // the release pipeline would see.
  rmSync(join(ROOT, '.next'), { recursive: true, force: true })
  const res = spawnSync(
    'node',
    ['node_modules/next/dist/bin/next', 'build'],
    {
      env: cleanEnv(),
      cwd: ROOT,
      encoding: 'utf-8',
      timeout: 600_000,
      maxBuffer: 64 * 1024 * 1024,
    }
  )
  buildStatus = res.status
  buildOutput = stripAnsi(`${res.stdout ?? ''}\n${res.stderr ?? ''}`)
  if (buildStatus !== 0) {
    throw new Error(
      `next build exited with ${buildStatus}:\n${buildOutput.slice(-8000)}`
    )
  }

  server = spawn(
    'node',
    ['node_modules/next/dist/bin/next', 'start', '-p', String(PORT)],
    { env: cleanEnv(), cwd: ROOT, stdio: 'pipe', detached: true }
  )
  server.stdout?.on('data', (c) => (serverLog += String(c)))
  server.stderr?.on('data', (c) => (serverLog += String(c)))

  const deadline = Date.now() + 90_000
  for (;;) {
    try {
      const r = await fetch(ORIGIN, { signal: AbortSignal.timeout(2000) })
      if (r.status < 500) break
    } catch {
      // not up yet
    }
    if (Date.now() > deadline) {
      throw new Error(`next start never became ready on ${PORT}:\n${serverLog}`)
    }
    await new Promise((r) => setTimeout(r, 500))
  }
}, 800_000)

afterAll(() => {
  if (server?.pid) {
    try {
      process.kill(-server.pid, 'SIGKILL')
    } catch {
      try {
        server.kill('SIGKILL')
      } catch {}
    }
  }
})

test('production build succeeds on the default bundler', () => {
  expect(buildStatus).toBe(0)
  // Capture sanity: these anchors must be present in a real default-bundler
  // build, so the warning checks below can never pass vacuously.
  expect(buildOutput).toMatch(/\(Turbopack\)/)
  expect(buildOutput).toMatch(/Compiled successfully/)
  expect(buildOutput).toMatch(/Generating static pages/)
})

test('build output contains zero warnings', () => {
  const excerpt = () => {
    const i = buildOutput.search(/Turbopack build encountered|Module not found|⚠/i)
    return i === -1 ? '' : `\n---\n${buildOutput.slice(Math.max(0, i - 200), i + 600)}\n---`
  }
  expect(
    /Turbopack build encountered/i.test(buildOutput),
    `build output still contains a Turbopack issue block${excerpt()}`
  ).toBe(false)
  expect(
    /Module not found/i.test(buildOutput),
    `build output still contains a module-not-found warning${excerpt()}`
  ).toBe(false)
  expect(
    /⚠/.test(buildOutput),
    `build output contains a warning line${excerpt()}`
  ).toBe(false)
})

test('the vendored client is byte-identical', () => {
  expect(existsSync(join(ROOT, VENDOR_PATH))).toBe(true)
  expect(read(VENDOR_PATH)).toBe(VENDOR_EXPECTED)
})

test('the vendored client still loads through the bundler, not a shim', () => {
  // (a) Some first-party source module still statically imports/requires the
  // vendored file by path (any import style and any specifier prefix is
  // accepted: relative, or the tsconfig `@/` alias).
  const importShape =
    /(?:\bfrom\s*|\brequire\s*\(\s*|\bimport\s*\(?\s*)['"][^'"]*vendor\/telemetry-client/
  const sources = walkFiles(ROOT, /\.(ts|tsx|js|jsx|mjs|cjs)$/, [
    'node_modules',
    '.next',
    'vendor',
  ]).filter((p) => !/EVAL/.test(relative(ROOT, p)))
  const importers = sources.filter((p) =>
    importShape.test(stripComments(readFileSync(p, 'utf-8')))
  )
  expect(
    importers.length,
    'no source file statically imports vendor/telemetry-client anymore — the module must keep loading exactly as it does today'
  ).toBeGreaterThan(0)

  // (b) The vendored module was actually compiled into the server bundle.
  // Loading it through eval('require')/createRequire escapes (or rendering a
  // hardcoded fallback marker) drops it from the bundler graph, which is what
  // produced the warning in the first place.
  const serverChunks = walkFiles(join(ROOT, '.next', 'server'), /\.(js|cjs)$/, [])
  const fingerprint = serverChunks.some((p) =>
    readFileSync(p, 'utf-8').includes('TELEMETRY_BACKEND')
  )
  expect(
    fingerprint,
    'the vendored client is no longer part of the compiled server bundle'
  ).toBe(true)
})

test('the warning is suppressed, not swallowed: no output-stream tampering', () => {
  // next.config.* (and anything it imports) executes inside the `next build`
  // process, so patching process.stdout/stderr writes or console methods can
  // hide the warning from the captured output without suppressing anything.
  // No legitimate solution needs any of these shapes anywhere in first-party
  // code: a real issue-suppression config never references the output
  // streams, never imports the process module, and never reassigns console
  // methods. Bans are shape-based and comment-stripped, so prose mentioning
  // these names stays legal.
  const bans: Array<[RegExp, string]> = [
    [
      /\bprocess\s*\.\s*(?:stdout|stderr)\b/,
      'references process.stdout/stderr',
    ],
    [
      /(?:\bfrom\s*|\brequire\s*\(\s*|\bimport\s*\(?\s*)['"](?:node:)?process['"]/,
      'imports the process module',
    ],
    [
      /\bconsole\s*\.\s*[A-Za-z_$][\w$]*\s*=(?!=)/,
      'reassigns a console method',
    ],
    [
      /\b(?:defineProperty|defineProperties|assign)\s*\(\s*console\b/,
      'patches the console object',
    ],
  ]
  const sources = walkFiles(ROOT, /\.(ts|tsx|js|jsx|mjs|cjs)$/, [
    'node_modules',
    '.next',
    'vendor',
  ]).filter((p) => !/EVAL/.test(relative(ROOT, p)))
  for (const p of sources) {
    const code = stripComments(readFileSync(p, 'utf-8'))
    for (const [re, what] of bans) {
      expect(
        re.test(code),
        `${relative(ROOT, p)} ${what} — the warning must be suppressed, not swallowed from the build output`
      ).toBe(false)
    }
  }
})

test('the build script is untouched and no webpack config sneaks in', () => {
  const pkg = JSON.parse(read('package.json'))
  expect(pkg.scripts?.build).toBe('next build')
  expect(JSON.stringify(pkg.scripts)).not.toMatch(/webpack/i)

  const configs = [
    'next.config.ts',
    'next.config.js',
    'next.config.mjs',
    'next.config.cjs',
  ].filter((p) => existsSync(join(ROOT, p)))
  expect(configs.length).toBeGreaterThan(0)
  for (const p of configs) {
    expect(stripComments(read(p)), `webpack config key in ${p}`).not.toMatch(
      /\bwebpack\s*:/
    )
  }
})

