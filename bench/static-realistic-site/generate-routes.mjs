#!/usr/bin/env node
// Writes the generated routes: `BENCH_ROUTES` (default 400) directories
// `app/[locale]/(gen)/s/<name>/[slug]/page.js`, each a route of its own with
// `generateStaticParams` and `generateMetadata`. Every fourth one has a
// layout. Run it before compiling; routes left from an earlier run are
// removed. The output is deterministic.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { sectionNames } from './lib/content.mjs'

const root = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  'app/[locale]/(gen)/s'
)
const n =
  process.env.BENCH_ROUTES === undefined
    ? 400
    : Number(process.env.BENCH_ROUTES)
fs.rmSync(root, { recursive: true, force: true })
sectionNames(n).forEach((name, index) => {
  const dir = path.join(root, name)
  fs.mkdirSync(path.join(dir, '[slug]'), { recursive: true })
  fs.writeFileSync(
    path.join(dir, '[slug]/page.js'),
    `// Generated by generate-routes.mjs.
import {
  SectionPage,
  sectionMetadata,
  sectionParams,
} from '../../../../../../components/section'

const NAME = '${name}'

export const generateStaticParams = (props) =>
  sectionParams(NAME, ${index}, props)
export const generateMetadata = (props) => sectionMetadata(NAME, props)

export default function Page({ params }) {
  return <SectionPage name={NAME} params={params} />
}
`
  )
  if (index % 4 === 0) {
    fs.writeFileSync(
      path.join(dir, 'layout.js'),
      `// Generated by generate-routes.mjs.
import { SectionLayout } from '../../../../../components/section'

export default function Layout({ children }) {
  return <SectionLayout name="${name}">{children}</SectionLayout>
}
`
    )
  }
})
console.log(`generate-routes: ${n} routes in ${root}`)
