import type { CompiledTestArtifact } from '../contracts'
import type { MockCoverageSources } from './types'
import { createHash } from 'crypto'
import { fileURLToPath, pathToFileURL } from 'url'

function sourceIdentity(value: unknown): value is string {
  if (typeof value !== 'string' || value.includes('\0')) return false
  if (value.startsWith('turbopack:///[project]/')) return true
  try {
    const file = fileURLToPath(value)
    return !file.includes('\0') && pathToFileURL(file).href === value
  } catch {
    return false
  }
}

export function validateMockCoverageSources(
  value: unknown
): asserts value is MockCoverageSources {
  const data = value as MockCoverageSources | undefined
  if (data?.version !== 1 || !Array.isArray(data.sources))
    throw new Error(
      'Mock coverage requires native generated-source provenance.'
    )
  const seen = new Set<string>()
  for (const source of data.sources) {
    if (
      !sourceIdentity(source?.source) ||
      seen.has(source.source) ||
      !/^[a-f0-9]{64}$/.test(source.sha256)
    )
      throw new Error('Invalid or duplicate native mock coverage source.')
    seen.add(source.source)
  }
}
/** Native records are the same strings passed to the generated VirtualSource. */
export function readNativeMockCoverageSources(
  value: unknown
): MockCoverageSources {
  const data = value as
    | { version?: unknown; sources?: { source?: unknown; code?: unknown }[] }
    | undefined
  if (data?.version !== 1 || !Array.isArray(data.sources))
    throw new Error(
      'Mock coverage requires a native binding with generated-source provenance.'
    )
  const sources = data.sources.map((entry) => {
    if (!sourceIdentity(entry?.source) || typeof entry.code !== 'string')
      throw new Error('Invalid native generated mock source.')
    return {
      source: entry.source,
      sha256: createHash('sha256').update(entry.code).digest('hex'),
    }
  })
  const result = { version: 1 as const, sources }
  validateMockCoverageSources(result)
  return result
}
/** A parent option cannot certify a native mock graph or erase unknown sources. */
export function assertMockCoverageArtifact(artifact: CompiledTestArtifact) {
  const synthetic = artifact.coverage?.syntheticSources ?? {}
  if (!artifact.moduleMocking) {
    if (Object.keys(synthetic).length)
      throw new Error('Unrequested synthetic coverage source provenance.')
    return
  }
  if (
    artifact.moduleMocking.version !== 1 ||
    artifact.kind !== 'node' ||
    artifact.profile.environment !== 'node' ||
    artifact.profile.mode !== 'development' ||
    artifact.profile.route !== undefined ||
    artifact.moduleCache ||
    artifact.cohort
  )
    throw new Error(
      'Mock coverage requires isolated development Node static mocks.'
    )
  validateMockCoverageSources(artifact.moduleMocking.coverage)
  const native = artifact.moduleMocking.coverage.nativeMetadata
  if (
    !native ||
    typeof native.path !== 'string' ||
    !artifact.files.includes(native.path) ||
    !/^[a-f0-9]{64}$/.test(native.sha256)
  )
    throw new Error(
      'Mock coverage requires its immutable native source inventory.'
    )
  const declared = new Map(
    artifact.moduleMocking.coverage.sources.map((source) => [
      source.source,
      source.sha256,
    ])
  )
  for (const [source, sha256] of declared) {
    if (
      Object.hasOwn(artifact.coverage?.sources ?? {}, source) &&
      (artifact.coverage?.sources[source] !== null ||
        synthetic[source]?.sha256 !== sha256)
    )
      throw new Error(
        'Mapped generated source lost its native coverage provenance.'
      )
  }
  for (const [source, value] of Object.entries(synthetic))
    if (
      !value ||
      declared.get(source) !== value.sha256 ||
      artifact.coverage?.sources[source] !== null
    )
      throw new Error(
        'Synthetic coverage source is not bound to its native generated bytes.'
      )
}

/** Re-read the retained native sidecar before capture and after worker closure. */
export function assertNativeMockCoverageBytes(
  artifact: CompiledTestArtifact,
  bytes: Buffer
) {
  const proof = artifact.moduleMocking?.coverage
  if (!proof) throw new Error('Missing native mock coverage inventory.')
  if (
    createHash('sha256').update(bytes).digest('hex') !==
    proof.nativeMetadata.sha256
  )
    throw new Error('Native mock coverage inventory changed after compilation.')
  const emitted = readNativeMockCoverageSources(
    JSON.parse(bytes.toString('utf8')).moduleMocking?.coverage
  )
  if (JSON.stringify(emitted.sources) !== JSON.stringify(proof.sources))
    throw new Error(
      'Mock coverage sources differ from the retained native inventory.'
    )
}
