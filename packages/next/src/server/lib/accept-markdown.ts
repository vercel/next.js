/**
 * Helpers for `experimental.acceptMarkdown`: App Router pages may export a
 * `markdown` string or function that is served instead of the rendered page
 * to requests that prefer `Accept: text/markdown`.
 */

export const MARKDOWN_CONTENT_TYPE = MARKDOWN_CONTENT_TYPE_HEADER

/** File suffix of the prerendered alternate, written next to the page's `.html`. */
export const MARKDOWN_SUFFIX = '.md'

export type MarkdownExport =
  | string
  | ((props: {
      params: Promise<Record<string, string | string[] | undefined>>
      searchParams: Promise<Record<string, string | string[] | undefined>>
    }) => string | Promise<string>)

export class AcceptMarkdownError extends Error {
  constructor(page: string, message: string) {
    super(`\`experimental.acceptMarkdown\`: page "${page}" ${message}`)
    this.name = 'AcceptMarkdownError'
  }
}

/** Loads the leaf page module of a loader tree (following `children`). */
export async function getPageModule(
  loaderTree: LoaderTree
): Promise<any | undefined> {
  let node: LoaderTree | undefined = loaderTree
  while (node) {
    const { page: pageModule } = node[2]
    if (pageModule) return pageModule[0]()
    node = node[1].children
  }
  return undefined
}

/**
 * Returns the `markdown` export of the leaf page module of a loader tree, or
 * `undefined` when the page doesn't define one.
 */
export async function getPageMarkdownExport(
  loaderTree: LoaderTree,
  page: string
): Promise<MarkdownExport | undefined> {
  const mod = await getPageModule(loaderTree)
  if (!mod) return undefined
  if (isClientReference(mod)) {
    if ('markdown' in mod) {
      throw new AcceptMarkdownError(
        page,
        `can't export \`markdown\` from a "use client" page.`
      )
    }
    return undefined
  }
  const exp = mod.markdown
  if (exp === undefined) return undefined
  if (typeof exp === 'string' || typeof exp === 'function') return exp
  throw new AcceptMarkdownError(
    page,
    `exports \`markdown\` as ${typeof exp}; expected a string or a function returning a string.`
  )
}

type Params = Record<string, string | string[] | undefined>

function paramKey(value: unknown): string {
  return JSON.stringify(
    Array.isArray(value)
      ? value.map(String)
      : value === undefined
        ? null
        : String(value)
  )
}

/**
 * Dev only: whether `params` were generated by `generateStaticParams` along
 * the page's loader-tree chain (layouts and page), so dev only serves
 * alternates for paths a production build would prerender. Every dynamic
 * segment of the route must be produced by some `generateStaticParams`.
 */
export async function isGeneratedParams(
  loaderTree: LoaderTree,
  params: Params
): Promise<boolean> {
  const paramNames: string[] = []
  let combinations: Params[] = [{}]
  let node: LoaderTree | undefined = loaderTree
  while (node) {
    const segmentParam = getSegmentParam(node[0])
    if (segmentParam) paramNames.push(segmentParam.paramName)

    const { mod } = await getLayoutOrPageModule(node)
    if (
      mod &&
      !isClientReference(mod) &&
      typeof mod.generateStaticParams === 'function'
    ) {
      const next: Params[] = []
      for (const parent of combinations) {
        const generated: Params[] =
          (await mod.generateStaticParams({ params: parent })) ?? []
        for (const child of generated) next.push({ ...parent, ...child })
      }
      combinations = next
    }
    // A page segment's module is the page itself; stop after it.
    if (node[2].page) break
    node = node[1].children
  }

  return combinations.some((candidate) =>
    paramNames.every(
      (name) =>
        name in candidate &&
        paramKey(candidate[name]) === paramKey(params[name])
    )
  )
}

/**
 * Resolves a `markdown` export to its content. `searchParams` isn't available
 * because alternates are static: reading it throws.
 */
export async function resolveMarkdown(
  exp: MarkdownExport,
  page: string,
  params: Record<string, string | string[] | undefined>
): Promise<string> {
  if (typeof exp === 'string') return exp

  const searchParams = {
    then() {
      throw new AcceptMarkdownError(
        page,
        `reads \`searchParams\` in \`markdown()\`; alternates are static and can't use request data.`
      )
    },
  } as unknown as Promise<Record<string, string | string[] | undefined>>

  let result: unknown
  try {
    result = await exp({ params: Promise.resolve(params), searchParams })
  } catch (err) {
    if (err instanceof AcceptMarkdownError) throw err
    throw new AcceptMarkdownError(
      page,
      `failed to generate its markdown alternate. \`markdown()\` must be static: it can't use request APIs like \`headers()\`, \`cookies()\`, \`connection()\` or \`draftMode()\`.\n${err instanceof Error ? err.message : String(err)}`
    )
  }
  if (typeof result !== 'string') {
    throw new AcceptMarkdownError(
      page,
      `\`markdown()\` returned ${result === null ? 'null' : typeof result}; expected a string.`
    )
  }
  return result
}

type MediaRange = { type: string; q: number }

function parseAccept(accept: string): MediaRange[] {
  const ranges: MediaRange[] = []
  for (const part of accept.split(',')) {
    const [rawType, ...rawParams] = part.split(';')
    const type = rawType.trim().toLowerCase()
    if (!type) continue
    let q = 1
    for (const param of rawParams) {
      const [key, value] = param.split('=')
      if (key?.trim().toLowerCase() === 'q') {
        const parsed = Number(value?.trim())
        q = Number.isFinite(parsed) ? Math.min(Math.max(parsed, 0), 1) : 0
      }
    }
    ranges.push({ type, q })
  }
  return ranges
}

/**
 * Whether an `Accept` header prefers Markdown over HTML: `text/markdown` must be
 * listed explicitly with q > 0, and its q must be at least the highest q among
 * `text/html`, `text/*` and `*\/*`. Ties go to Markdown; wildcards alone don't
 * select Markdown.
 */
export function prefersMarkdown(
  accept: string | string[] | undefined
): boolean {
  if (!accept) return false
  const header = Array.isArray(accept) ? accept.join(',') : accept
  let markdown = -1
  let html = 0
  for (const { type, q } of parseAccept(header)) {
    if (type === 'text/markdown') markdown = Math.max(markdown, q)
    else if (type === 'text/html' || type === 'text/*' || type === '*/*') {
      html = Math.max(html, q)
    }
  }
  return markdown > 0 && markdown >= html
}

/**
 * Reads the alternate prerendered for `pathname` at build time, or `undefined`
 * when none was written (Node.js runtime only).
 */
export async function readPrerenderedMarkdown(
  relativeProjectDir: string,
  distDir: string,
  pathname: string
): Promise<string | undefined> {
  if (process.env.NEXT_RUNTIME === 'edge') return undefined
  const { join } = require('node:path') as typeof import('node:path')
  const { readFile } =
    require('node:fs/promises') as typeof import('node:fs/promises')
  const file = join(
    /* turbopackIgnore: true */
    process.cwd(),
    relativeProjectDir,
    distDir,
    'server',
    'app',
    `${normalizePagePath(pathname)}${MARKDOWN_SUFFIX}`
  )
  try {
    return await readFile(/* turbopackIgnore: true */ file, 'utf8')
  } catch (err: any) {
    if (err?.code === 'ENOENT') return undefined
    throw err
  }
}
