// @ts-check
// Compile the upstream UI without importing React Grab's selection backend.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, readFile, realpath, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const upstreamCommit = 'ea4bbec9e80f4802e8ae19ad18431edb9ddbb670'
const upstreamVersion = '0.2.0'
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const nextRoot = join(repoRoot, 'packages/next')
const require = createRequire(join(nextRoot, 'package.json'))
// Resolve explicitly because build dependencies belong to packages/next.
const { build } = require(require.resolve('esbuild'))
const { transformAsync } = require('@babel/core')
const ts = require('typescript')

if (!process.argv[2]) {
  throw new Error(
    'Usage: node scripts/build-react-grab-frontend.mjs /path/to/react-grab'
  )
}

const sourceRoot = await realpath(resolve(process.argv[2]))
const actualCommit = execFileSync('git', ['rev-parse', 'HEAD'], {
  cwd: sourceRoot,
  encoding: 'utf8',
}).trim()
if (actualCommit !== upstreamCommit) {
  throw new Error(`Expected React Grab ${upstreamCommit}, got ${actualCommit}`)
}
const sourceChanges = execFileSync(
  'git',
  [
    'status',
    '--porcelain',
    '--untracked-files=all',
    '--',
    'packages/react-grab',
  ],
  { cwd: sourceRoot, encoding: 'utf8' }
).trim()
if (sourceChanges) {
  throw new Error('The pinned React Grab source checkout must be unchanged')
}

const sourceDir = join(sourceRoot, 'packages/react-grab/src')
const outputDir = join(nextRoot, 'src/compiled/react-grab-frontend')
const npmRoot = dirname(require.resolve('react-grab/package.json'))
const solidRoot = dirname(require.resolve('solid-js/package.json'))
const npmPackage = JSON.parse(
  await readFile(join(npmRoot, 'package.json'), 'utf8')
)
if (npmPackage.version !== upstreamVersion) {
  throw new Error(`Expected published react-grab@${upstreamVersion}`)
}
const styles = await readFile(join(npmRoot, 'dist/styles.css'), 'utf8')

// These are backend boundaries, not replacements for upstream UI components.
// Next owns all Fiber access, selection, source resolution, and WebMCP state.
const boundaries = new Map([
  ['utils/freeze-updates.ts', 'export const freezeUpdates = () => () => {}'],
  [
    'utils/freeze-global-interactions.ts',
    'export const freezeGlobalInteractions = () => {}; export const unfreezeGlobalInteractions = () => {}',
  ],
  ['core/element-adapter.ts', 'export const getElementAdapter = () => null'],
])
// The upstream canvas palette is not CSS-based. Supply Next's blue-700 token
// through its existing color helper while keeping every renderer unchanged.
const palette = '0, 112, 243'
const substitutions = new Map([
  ...boundaries,
  [
    'utils/overlay-color.ts',
    `export const overlayColor = (alpha) => 'rgba(${palette}, ' + alpha + ')'`,
  ],
])

const result = await build({
  absWorkingDir: sourceDir,
  stdin: {
    resolveDir: sourceDir,
    sourcefile: 'next-react-grab-renderer-adapter.ts',
    loader: 'ts',
    contents: `
      import { createSignal } from 'solid-js'
      import { render } from 'solid-js/web'
      import { ReactGrabRenderer } from './components/renderer.tsx'
      export const styles = ${JSON.stringify(styles)}

      export function mountReactGrabRenderer(root, initialProps) {
        const [read, write] = createSignal(initialProps)
        const props = new Proxy({}, { get: (_, name) => read()[name] })
        const unmount = render(() => ReactGrabRenderer(props), root)
        let disposed = false
        return {
          update(nextProps) {
            if (!disposed) write(() => nextProps)
          },
          dispose() {
            if (disposed) return
            disposed = true
            unmount()
          },
        }
      }
    `,
  },
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  minify: true,
  write: false,
  metafile: true,
  legalComments: 'none',
  define: {
    'process.env.NODE_ENV': '"production"',
    'process.env.IS_DEMO': '""',
    'process.env.VERSION': JSON.stringify(upstreamVersion),
    'process.env.REACT_GRAB_SOURCE_LOCATIONS': '""',
  },
  banner: {
    js: `/*! React Grab ${upstreamVersion} (${upstreamCommit}) frontend and SolidJS. MIT. See LICENSE. Generated by scripts/build-react-grab-frontend.mjs. */`,
  },
  plugins: [
    {
      name: 'next-react-grab-frontend',
      setup(builder) {
        builder.onResolve({ filter: /^solid-js(?:\/web)?$/ }, ({ path }) => ({
          path: join(
            solidRoot,
            path === 'solid-js' ? 'dist/solid.js' : 'web/dist/web.js'
          ),
        }))
        builder.onResolve({ filter: /^\./ }, ({ path, importer }) => {
          const sourcePath = relative(
            sourceDir,
            resolve(dirname(importer), path)
          ).replace(/\.jsx?$/, '.ts')
          if (substitutions.has(sourcePath)) {
            return {
              path: sourcePath,
              namespace: 'next-react-grab-adapter',
            }
          }
        })
        builder.onLoad(
          { filter: /.*/, namespace: 'next-react-grab-adapter' },
          ({ path }) => ({ contents: substitutions.get(path), loader: 'js' })
        )
        builder.onLoad({ filter: /\.[jt]sx$/ }, async ({ path }) => {
          const transformed = await transformAsync(
            await readFile(path, 'utf8'),
            {
              filename: path,
              babelrc: false,
              configFile: false,
              presets: [
                [
                  require.resolve('@babel/preset-typescript'),
                  { onlyRemoveTypeImports: true },
                ],
                require.resolve('babel-preset-solid'),
              ],
              caller: {
                name: 'next-react-grab-frontend',
                supportsStaticESM: true,
              },
            }
          )
          if (!transformed?.code) throw new Error(`Could not compile ${path}`)
          return { contents: transformed.code, loader: 'js' }
        })
      },
    },
  ],
})

const inputs = Object.keys(result.metafile.inputs).sort()
for (const input of inputs) {
  if (input.startsWith('next-react-grab-adapter:')) continue
  if (
    input.includes('bippy') ||
    /(^|\/)core\//.test(input) ||
    /(^|\/)(freeze-updates|freeze-global-interactions)\.[jt]s$/.test(input)
  ) {
    throw new Error(`React Grab backend entered the frontend build: ${input}`)
  }
}
/** @type {Record<string, { imports: unknown[] }>} */
const outputs = result.metafile.outputs
for (const output of Object.values(outputs)) {
  if (output.imports.length !== 0) {
    throw new Error('The React Grab frontend must be a self-contained bundle')
  }
}
const bundle = result.outputFiles[0].text
if (
  /__REACT_DEVTOOLS_GLOBAL_HOOK__|react-grab-freeze-updates|bippy/.test(bundle)
) {
  throw new Error(
    'Fiber instrumentation entered the React Grab frontend bundle'
  )
}

// Preserve the exact upstream renderer types and their transitive declarations.
// The selected declarations have only DOM references; they require no Solid types.
const typeSource = ts.createSourceFile(
  'types.ts',
  await readFile(join(sourceDir, 'types.ts'), 'utf8'),
  ts.ScriptTarget.Latest,
  true
)
const declarations = new Map()
for (const statement of typeSource.statements) {
  if (
    ts.isInterfaceDeclaration(statement) ||
    ts.isTypeAliasDeclaration(statement)
  ) {
    declarations.set(statement.name.text, statement)
  }
}
const included = new Set()
function includeType(name) {
  if (included.has(name)) return
  const declaration = declarations.get(name)
  if (!declaration) return
  included.add(name)
  function visit(node) {
    if (ts.isIdentifier(node)) includeType(node.text)
    ts.forEachChild(node, visit)
  }
  ts.forEachChild(declaration, visit)
}
includeType('ReactGrabRendererProps')
const declarationText = [...included]
  .map((name) => declarations.get(name).getText(typeSource))
  .join('\n\n')
const types = `// Generated from React Grab ${upstreamVersion} (${upstreamCommit}). MIT; see LICENSE.
${declarationText}

export interface ReactGrabRendererHandle {
  update(props: ReactGrabRendererProps): void
  dispose(): void
}
export declare const styles: string
export declare function mountReactGrabRenderer(
  root: HTMLElement,
  initialProps: ReactGrabRendererProps
): ReactGrabRendererHandle
`

const licenses = await Promise.all([
  readFile(join(npmRoot, 'LICENSE'), 'utf8'),
  readFile(join(solidRoot, 'LICENSE'), 'utf8'),
])
const provenance = {
  upstream: 'https://github.com/aidenybai/react-grab',
  commit: upstreamCommit,
  version: upstreamVersion,
  stylesSha256: createHash('sha256').update(styles).digest('hex'),
  backendBoundaries: [...boundaries.keys()],
  palette: {
    module: 'utils/overlay-color.ts',
    rgb: palette,
    token: 'blue-700',
  },
  buildDependencies: Object.fromEntries(
    [
      'esbuild',
      '@babel/core',
      '@babel/preset-typescript',
      'babel-preset-solid',
      'solid-js',
    ].map((name) => [name, require(`${name}/package.json`).version])
  ),
  upstreamInputs: inputs.filter(
    (input) =>
      !input.startsWith('../') &&
      !input.includes(':') &&
      input !== 'next-react-grab-renderer-adapter.ts'
  ),
}
await mkdir(outputDir, { recursive: true })
await Promise.all([
  writeFile(join(outputDir, 'index.js'), bundle),
  writeFile(join(outputDir, 'index.d.ts'), types),
  writeFile(join(outputDir, 'LICENSE'), licenses.join('\n\n---\n\n')),
  writeFile(
    join(outputDir, 'package.json'),
    JSON.stringify(
      {
        name: 'react-grab-frontend',
        version: upstreamVersion,
        main: 'index.js',
        types: 'index.d.ts',
        license: 'MIT',
      },
      null,
      2
    ) + '\n'
  ),
  writeFile(
    join(outputDir, 'provenance.json'),
    JSON.stringify(provenance, null, 2) + '\n'
  ),
])
console.log(
  `Built upstream React Grab frontend (${inputs.length} modules); no Fiber/backend imports.`
)
