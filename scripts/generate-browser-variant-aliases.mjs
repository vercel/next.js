// @ts-check
/**
 * Generates the list of Next.js modules that have a browser-specific variant,
 * i.e. a `<module>.ts` (the default, used on the server and any unbundled
 * runtime) paired with a sibling `<module>.browser.ts`. The browser bundle is
 * aliased to the `.browser` variant by both bundlers:
 *
 *   - webpack:   packages/next/src/build/create-compiler-aliases.ts
 *   - Turbopack: crates/next-core/src/next_import_map.rs
 *
 * Both consumers read the generated lists produced here so the set stays in
 * sync with the filesystem. Run with `--check` (used in CI) to verify the
 * committed lists are up to date without writing.
 *
 * Usage:
 *   node scripts/generate-browser-variant-aliases.mjs           # write
 *   node scripts/generate-browser-variant-aliases.mjs --check   # verify
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs'
import { join, relative, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..')
const srcDir = join(repoRoot, 'packages/next/src')
const tsOut = join(srcDir, 'build/browser-variant-modules.ts')
const rsOut = join(repoRoot, 'crates/next-core/src/browser_variant_modules.rs')

/** Recursively collect every file path under `dir`. */
function walk(dir) {
  /** @type {string[]} */
  const files = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...walk(full))
    else files.push(full)
  }
  return files
}

/**
 * Scan for `<module>.browser.{ts,tsx}` files that have a base `<module>.{ts,tsx}`
 * sibling, returning posix module paths relative to `packages/next/src` without
 * an extension (e.g. `client/components/unstable-rethrow`).
 */
function collectModules() {
  /** @type {string[]} */
  const modules = []
  for (const file of walk(srcDir)) {
    const match = file.match(/^(.*)\.browser\.tsx?$/)
    if (!match) continue
    const stem = match[1]
    if (!existsSync(`${stem}.ts`) && !existsSync(`${stem}.tsx`)) continue
    modules.push(relative(srcDir, stem).split('\\').join('/'))
  }
  return modules.sort()
}

function renderTs(modules) {
  const entries = modules.map((m) => `  '${m}',`).join('\n')
  return `// This file is @generated by \`pnpm generate-browser-variant-aliases\`.
// Do not edit by hand.
//
// Modules with a \`.browser\` sibling. The default module is aliased to its
// \`.browser\` variant for the browser bundle in
// \`packages/next/src/build/create-compiler-aliases.ts\`. Paths are relative to
// \`packages/next/dist\` (extension omitted).
export const browserVariantModules = [
${entries}
] as const
`
}

function renderRust(modules) {
  const entries = modules.map((m) => `    "${m}",`).join('\n')
  return `//! This file is @generated by \`pnpm generate-browser-variant-aliases\`.
//! Do not edit by hand.
//!
//! Modules with a \`.browser\` sibling. The default module is aliased to its
//! \`.browser\` variant for the browser bundle in
//! \`get_next_client_resolved_map\` (see \`next_import_map.rs\`). Paths are
//! relative to \`next/dist\` (extension omitted).

// rustfmt::skip keeps this list one-per-line (and matching the generator
// output) instead of collapsing short lists onto a single line.
#[rustfmt::skip]
pub static BROWSER_VARIANT_MODULES: &[&str] = &[
${entries}
];
`
}

/** Extract the quoted module list from a generated file for comparison. */
function parseModules(contents) {
  // Quoted strings only appear as list entries; doc comments use backticks.
  return [...contents.matchAll(/["']([^"']+)["']/g)].map((m) => m[1]).sort()
}

const modules = collectModules()
const check = process.argv.includes('--check')

if (check) {
  let ok = true
  for (const [out, label] of [
    [tsOut, 'TypeScript'],
    [rsOut, 'Rust'],
  ]) {
    const onDisk = existsSync(out)
      ? parseModules(readFileSync(out, 'utf8'))
      : []
    if (JSON.stringify(onDisk) !== JSON.stringify(modules)) {
      ok = false
      console.error(
        `${label} browser-variant list is out of date (${out}).\n` +
          `  expected: ${JSON.stringify(modules)}\n` +
          `  on disk:  ${JSON.stringify(onDisk)}`
      )
    }
  }
  if (!ok) {
    console.error(
      '\nRun `pnpm generate-browser-variant-aliases` to update the generated lists.'
    )
    process.exit(1)
  }
  console.log('browser-variant lists are up to date.')
} else {
  writeFileSync(tsOut, renderTs(modules))
  writeFileSync(rsOut, renderRust(modules))
  console.log(
    `Generated ${modules.length} browser-variant module(s):\n  ${modules.join('\n  ')}`
  )
}
