import { nextTestSetup } from 'e2e-utils'
import { retry } from 'next-test-utils'
import { createRouterAct } from 'router-act'
import type * as Playwright from 'playwright'
import { randomUUID } from 'node:crypto'
import { load } from 'cheerio'

describe('Cache Components static navigation', () => {
  const { next } = nextTestSetup({ files: __dirname })

  function pathname(kind: string, slug: string) {
    return '/cache-components-static-navigation/' + kind + '/' + slug
  }

  async function read(path: string) {
    const response = await next.fetch(path)
    expect(response.status).toBe(200)
    const $ = load(await response.text())
    return {
      value: $('#value').text(),
      dynamic: $('#dynamic').text(),
      cache: response.headers.get('x-nextjs-cache'),
      postponed: response.headers.get('x-nextjs-postponed'),
    }
  }

  async function warm(path: string) {
    return retry(async () => {
      const response = await read(path)
      expect(response.cache).toBe('HIT')
      expect(response.postponed).toBeNull()
      return response
    })
  }

  async function navigate(path: string) {
    let act: ReturnType<typeof createRouterAct>
    const responses: Playwright.Response[] = []
    const browser = await next.browser(
      '/hub?target=' + encodeURIComponent(path),
      {
        beforePageLoad(page: Playwright.Page) {
          act = createRouterAct(page)
          page.on('response', (response) => {
            const request = response.request()
            const headers = request.headers()
            if (
              new URL(request.url()).pathname === path &&
              headers.rsc === '1' &&
              headers['next-router-prefetch'] === undefined &&
              headers['next-action'] === undefined
            ) {
              responses.push(response)
            }
          })
        },
      }
    )
    try {
      await act(async () => {
        await browser.elementById('show-target').click()
        await browser.elementById('target').click()
      })
      expect(responses.length).toBeGreaterThan(0)
      const received = responses.map((response) => {
        expect(response.status()).toBe(200)
        return { headers: response.headers() }
      })
      return { browser, act, responses: received }
    } catch (error) {
      await browser.close()
      throw error
    }
  }

  async function expectCachedNavigation(path: string, value: string) {
    const navigation = await navigate(path)
    try {
      expect(await navigation.browser.elementById('value').text()).toBe(value)
      for (const response of navigation.responses) {
        expect(response.headers['x-nextjs-cache']).toBe('HIT')
        expect(response.headers['x-nextjs-prerender']).toBe('1')
      }
    } finally {
      await navigation.browser.close()
    }
  }

  it('serves a fresh prerender generated by a document request after a restart', async () => {
    const path = pathname('static', 'runtime-' + randomUUID())
    const { value } = await warm(path)
    expect(value).toStartWith('static:runtime-')
    await next.stop()
    await next.start({ skipBuild: true })
    await expectCachedNavigation(path, value)
  })

  it('serves complete cached RSC when a metadata-only request selects a fresh fully static entry', async () => {
    const path = pathname('static', 'metadata-' + randomUUID())
    const { value } = await warm(path)
    const response = await next.fetch(path, {
      headers: {
        rsc: '1',
        'next-router-state-tree': encodeURIComponent(
          JSON.stringify(['', {}, null, 'metadata-only'])
        ),
      },
    })
    expect(response.status).toBe(200)
    expect(response.headers.get('x-nextjs-cache')).toBe('HIT')
    expect(await response.text()).toContain(value)
  })

  it("reuses a partial prerender's cached value and renders its dynamic content for each navigation", async () => {
    const path = pathname('partial', 'built')
    const initial = await read(path)
    expect(initial.dynamic).not.toBe('')
    const navigation = await navigate(path)
    try {
      expect(await navigation.browser.elementById('value').text()).toBe(
        initial.value
      )
      expect(await navigation.browser.elementById('dynamic').text()).not.toBe(
        initial.dynamic
      )
      for (const response of navigation.responses) {
        expect(response.headers['x-nextjs-prerender']).toBeUndefined()
      }
    } finally {
      await navigation.browser.close()
    }
  })

  it('renders concrete router tree params for a shared shell with no server-side dynamic holes', async () => {
    const prefix = 'shared-' + randomUUID()
    const path = '/cache-components-static-navigation/shared/' + prefix
    await warm(path + '/first')

    // A different slug hits the same shell without a server resume.
    const sibling = await read(path + '/second')
    expect(sibling.cache).toBe('HIT')
    expect(sibling.postponed).toBeNull()

    const navigation = await navigate(path + '/third')
    try {
      expect(await navigation.browser.elementById('slug').text()).toBe('third')
    } finally {
      await navigation.browser.close()
    }
  })

  it('executes a Server Action when a fresh fully static entry is available', async () => {
    const path = pathname('static', 'action-' + randomUUID())
    await warm(path)
    const navigation = await navigate(path)
    try {
      await navigation.act(() =>
        navigation.browser.elementById('run-action').click()
      )
      await retry(async () => {
        expect(
          await navigation.browser.elementById('action-result').text()
        ).toBe('Action executed')
      })
    } finally {
      await navigation.browser.close()
    }
  })

  it('runtime-prerenders a runtime prefetch instead of serving a fresh cached RSC response', async () => {
    const path = pathname('static', 'prefetch-' + randomUUID())
    await warm(path)
    const response = await next.fetch(path, {
      headers: { rsc: '1', 'next-router-prefetch': '2' },
    })
    expect(response.status).toBe(200)
    expect(response.headers.get('x-nextjs-prerender')).toBeNull()
    expect(response.headers.get('x-nextjs-cache')).toBeNull()
    await response.text()
  })

  for (const state of ['stale', 'expired'] as const) {
    it(
      'renders dynamic RSC after tag revalidation marks the cached value ' +
        state,
      async () => {
        const slug = state + '-' + randomUUID()
        const path = pathname('static', slug)
        await warm(path)
        const response = await next.fetch(
          '/cache-components-static-navigation/revalidate',
          {
            method: 'POST',
            headers: { 'content-type': 'application/json' },
            body: JSON.stringify({
              tag: 'cache-components-static-navigation:static:' + slug,
              state,
            }),
          }
        )
        expect(response.status).toBe(204)

        const navigation = await navigate(path)
        try {
          for (const response of navigation.responses) {
            expect(response.headers['x-nextjs-prerender']).toBeUndefined()
            expect(response.headers['x-nextjs-cache']).toBeUndefined()
          }
        } finally {
          await navigation.browser.close()
        }
      }
    )
  }
})
