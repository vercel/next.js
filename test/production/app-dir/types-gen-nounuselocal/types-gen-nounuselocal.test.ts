import fsp from 'fs/promises'
import path from 'path'
import { nextTestSetup } from 'e2e-utils'

const strictRouteTypes =
  process.env.__NEXT_EXPERIMENTAL_STRICT_ROUTE_TYPES === 'true'

describe('types-gen-nounuselocal', () => {
  const { next, skipped } = nextTestSetup({
    files: __dirname,
  })

  if (skipped) {
    return
  }

  it('should build successfully', async () => {
    const $ = await next.render$('/')
    expect($('p').text()).toBe('hello world')
  })

  it('should generate route types successfully', async () => {
    const routeTypes = await fsp.readFile(
      path.join(next.testDir, '.next', 'types', 'routes.d.ts'),
      'utf-8'
    )

    expect(routeTypes).not.toContain('AppRouteHandlerRoutes')
    expect(routeTypes).not.toContain('PagesPageConfig')
    expect(routeTypes).not.toContain('ApiRouteConfig')

    if (strictRouteTypes) {
      const cacheLifeTypes = await fsp.readFile(
        path.join(next.testDir, '.next', 'types', 'cache-life.d.ts'),
        'utf-8'
      )
      expect(cacheLifeTypes).toContain("declare module 'next/cache'")

      expect(routeTypes).toMatchInlineSnapshot(`
       "// This file is generated automatically by Next.js with experimental.strictRouteTypes
       // Do not edit this file manually

       import 'next/types/routes'

       type AppRoutes = "/"
       type PageRoutes = never
       type LayoutRoutes = "/"
       type RedirectRoutes = never
       type RewriteRoutes = never
       type Routes = AppRoutes | PageRoutes | LayoutRoutes | RedirectRoutes | RewriteRoutes


       interface ParamMap {
         "/": {}
       }


       export type ParamsOf<Route extends Routes> = ParamMap[Route]

       interface LayoutSlotMap {
         "/": never
       }


       export type { AppRoutes, PageProps, PageRoutes, LayoutRoutes, RedirectRoutes, RewriteRoutes, ParamMap }

       declare global {
         namespace __NextRouteTypes {
           interface AppRoutesMap {
             "/": true
           }
           interface LayoutRoutesMap {
             "/": true
           }
           interface ParamMap {
             "/": {}
           }
         }
       }
       "
      `)
    } else {
      expect(routeTypes).toMatchInlineSnapshot(`
       "// This file is generated automatically by Next.js
       // Do not edit this file manually

       import 'next/types/routes'

       type AppRoutes = "/"
       type PageRoutes = never
       type LayoutRoutes = "/"
       type RedirectRoutes = never
       type RewriteRoutes = never
       type Routes = AppRoutes | PageRoutes | LayoutRoutes | RedirectRoutes | RewriteRoutes


       interface ParamMap {
         "/": {}
       }


       export type ParamsOf<Route extends Routes> = ParamMap[Route]

       interface LayoutSlotMap {
         "/": never
       }


       export type { AppRoutes, PageRoutes, LayoutRoutes, RedirectRoutes, RewriteRoutes, ParamMap }

       declare global {
         namespace __NextRouteTypes {
           interface AppRoutesMap {
             "/": true
           }
           interface LayoutRoutesMap {
             "/": true
           }
           interface ParamMap {
             "/": {}
           }
         }
       }
       "
      `)
    }
  })
})
