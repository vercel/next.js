// A webpack loader that returns invalid CSS with a source map.
// The source map points back to the original file, but the generated
// CSS is intentionally broken (unparseable).
module.exports = function (source) {
  // Generate a source map that maps back to the original source
  const sourceMap = {
    version: 3,
    sources: [this.resourcePath],
    sourcesContent: [source],
    // identity mapping
    mappings: 'AAAA;AACA;AACA;AACA',
    names: [],
  }

  // Return broken CSS that will fail to parse
  const brokenCss = `/* Generated by broken-css-loader */
.page {
  color: red
  @@@ THIS IS NOT VALID CSS @@@;
  background: {{{ invalid
}
`

  this.callback(null, brokenCss, sourceMap)
}
