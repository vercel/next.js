import { nextTestSetup } from 'e2e-utils'
import {
  NEXT_RSC_UNION_QUERY,
  RSC_HEADER,
} from 'next/dist/client/components/app-router-headers'

describe('experimental markdown output', () => {
  const { next } = nextTestSetup({
    files: __dirname,
  })

  it('keeps html by default for opted-in app routes', async () => {
    const response = await next.fetch('/app-basic')
    const html = await response.text()

    expect(response.headers.get('content-type')).toContain('text/html')
    expect(response.headers.get('vary')).toContain('Accept')
    expect(html).toContain('<h1>App Basic</h1>')
    expect(html).toContain('Ignore me')
  })

  it('returns markdown for opted-in app routes when markdown is preferred', async () => {
    const response = await next.fetch('/app-basic', {
      headers: {
        accept: 'text/markdown, text/html;q=0.9',
      },
    })
    const markdown = await response.text()

    expect(response.headers.get('content-type')).toBe(
      'text/markdown; charset=utf-8'
    )
    expect(response.headers.get('vary')).toContain('Accept')
    expect(markdown).toMatchInlineSnapshot(`
      "# App Basic

      root:App paragraph"
    `)
  })

  it('returns markdown for app routes generated by generateStaticParams', async () => {
    const response = await next.fetch('/app-static/alpha', {
      headers: {
        accept: 'text/markdown',
      },
    })

    expect(response.headers.get('content-type')).toBe(
      'text/markdown; charset=utf-8'
    )
    expect(response.headers.get('vary')).toContain('Accept')
    expect(await response.text()).toMatchInlineSnapshot(`
      "# App Static alpha

      root:Static paragraph alpha"
    `)
  })

  it('returns markdown headers for HEAD requests without a response body', async () => {
    const response = await next.fetch('/app-basic', {
      method: 'HEAD',
      headers: {
        accept: 'text/markdown',
      },
    })

    expect(response.headers.get('content-type')).toBe(
      'text/markdown; charset=utf-8'
    )
    expect(response.headers.get('vary')).toContain('Accept')
    expect(await response.text()).toBe('')
  })

  it('does not negotiate markdown for routes without opt-in', async () => {
    const response = await next.fetch('/', {
      headers: {
        accept: 'text/markdown',
      },
    })
    const html = await response.text()

    expect(response.headers.get('content-type')).toContain('text/html')
    expect(html).toContain('<h1>Home HTML Only</h1>')
  })

  it('composes app layouts bottom-up with child component precedence', async () => {
    const response = await next.fetch('/app-composed/inner', {
      headers: {
        accept: 'text/markdown',
      },
    })

    expect(await response.text()).toMatchInlineSnapshot(`
      "outer-start
      inner-start
      page:Nested value
      inner-end
      outer-end"
    `)
  })

  it('supports component-name overrides before tag overrides and can reintroduce interactive output', async () => {
    const response = await next.fetch('/app-override', {
      headers: {
        accept: 'text/markdown',
      },
    })
    const markdown = await response.text()

    expect(markdown).toMatchInlineSnapshot(`
      "action:Card

      component:Download

      root:Override paragraph"
    `)
    expect(markdown).not.toContain('tag:Download')
  })

  it('serializes SSR-able client components and still omits interactive controls by default', async () => {
    const response = await next.fetch('/app-client', {
      headers: {
        accept: 'text/markdown',
      },
    })
    const markdown = await response.text()

    expect(markdown).toMatchInlineSnapshot(`"root:Client paragraph"`)
    expect(markdown).not.toContain('Tap me')
  })

  it('does not enable markdown negotiation in the edge runtime', async () => {
    const response = await next.fetch('/app-edge', {
      headers: {
        accept: 'text/markdown',
      },
    })

    expect(response.headers.get('content-type')).toContain('text/html')
    expect(await response.text()).toContain('<h1>App Edge</h1>')
  })

  it('returns markdown for opted-in pages routes when markdown is preferred', async () => {
    const response = await next.fetch('/pages-basic', {
      headers: {
        accept: 'text/markdown',
      },
    })
    const markdown = await response.text()

    expect(response.headers.get('content-type')).toBe(
      'text/markdown; charset=utf-8'
    )
    expect(response.headers.get('vary')).toContain('Accept')
    expect(markdown).toMatchInlineSnapshot(`
      "# Pages Basic

      root:Pages paragraph"
    `)
  })

  it('keeps html by default for opted-in pages routes', async () => {
    const response = await next.fetch('/pages-basic')
    const html = await response.text()

    expect(response.headers.get('content-type')).toContain('text/html')
    expect(response.headers.get('vary')).toContain('Accept')
    expect(html).toContain('<h1>Pages Basic</h1>')
  })

  it('supports pages generateMarkdown with resolved props and query', async () => {
    const response = await next.fetch('/pages-custom?id=123', {
      headers: {
        accept: 'text/markdown',
      },
    })

    expect(await response.text()).toMatchInlineSnapshot(`
      "custom-start
      message:hello-123
      query:123
      default:root:hello-123
      custom-end"
    `)
  })

  it('keeps next data requests as json even when markdown is preferred', async () => {
    const response = await next.fetch(
      `/_next/data/${next.buildId}/pages-custom.json?id=123`,
      {
        headers: {
          accept: 'text/markdown',
        },
      }
    )

    expect(response.headers.get('content-type')).toContain('application/json')
    await expect(response.json()).resolves.toMatchObject({
      pageProps: {
        message: 'hello-123',
      },
    })
  })

  it('keeps rsc requests as flight payload even when markdown is preferred', async () => {
    const response = await next.fetch(`/app-basic?${NEXT_RSC_UNION_QUERY}`, {
      headers: {
        [RSC_HEADER]: '1',
        accept: 'text/markdown',
      },
    })
    const body = await response.text()

    expect(response.headers.get('content-type')).toBe('text/x-component')
    expect(body).toContain('__PAGE__')
    expect(body).not.toContain('# App Basic')
  })
})
