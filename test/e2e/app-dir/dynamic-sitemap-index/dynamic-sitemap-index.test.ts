import { nextTestSetup } from 'e2e-utils'

describe('dynamic-sitemap-index', () => {
  const { next } = nextTestSetup({
    files: __dirname,
  })

  describe('generateSitemaps with root sitemap.ts', () => {
    // This test verifies that individual sitemaps work correctly
    // when using generateSitemaps in the root app directory
    it('should serve individual sitemaps at /sitemap/[id].xml', async () => {
      // Test pages sitemap
      const pagesRes = await next.fetch('/sitemap/pages.xml')
      expect(pagesRes.status).toBe(200)
      expect(pagesRes.headers.get('content-type')).toBe('application/xml')
      const pagesText = await pagesRes.text()
      expect(pagesText).toContain('<loc>https://example.com</loc>')
      expect(pagesText).toContain('<loc>https://example.com/about</loc>')

      // Test blog sitemap
      const blogRes = await next.fetch('/sitemap/blog.xml')
      expect(blogRes.status).toBe(200)
      expect(blogRes.headers.get('content-type')).toBe('application/xml')
      const blogText = await blogRes.text()
      expect(blogText).toContain('<loc>https://example.com/blog/post-1</loc>')
      expect(blogText).toContain('<loc>https://example.com/blog/post-2</loc>')
    })

    // TODO: This test documents a known issue (https://github.com/vercel/next.js/issues/77304)
    // When using generateSitemaps() in the root sitemap.ts, /sitemap.xml should
    // return a sitemap index linking to all child sitemaps, but currently returns 404.
    // Once this issue is fixed, update this test to expect 200 and a proper sitemapindex.
    it('should return 404 for /sitemap.xml when using generateSitemaps (known issue #77304)', async () => {
      const res = await next.fetch('/sitemap.xml')

      // Current behavior (bug): /sitemap.xml returns 404
      // Expected behavior: /sitemap.xml should return a sitemap index (sitemapindex)
      // that links to the child sitemaps generated by generateSitemaps()
      //
      // When this issue is fixed, this test should be updated to:
      // - expect(res.status).toBe(200)
      // - expect(res.headers.get('content-type')).toBe('application/xml')
      // - expect(text).toContain('sitemapindex')
      // - expect(text).toContain('/sitemap/pages.xml')
      // - expect(text).toContain('/sitemap/blog.xml')
      expect(res.status).toBe(404)
    })

    it('should return 404 for non-existing sitemap id', async () => {
      const res = await next.fetch('/sitemap/non-existing.xml')
      expect(res.status).toBe(404)
    })

    it('should return 404 when accessing sitemap without .xml extension', async () => {
      const res = await next.fetch('/sitemap/pages')
      expect(res.status).toBe(404)
    })
  })
})
