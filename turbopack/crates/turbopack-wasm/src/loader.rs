/// Reserved words and strict-mode restricted bindings that cannot be used as
/// binding identifiers in an ES module.
static RESERVED_WORDS: &[&str] = &[
    // ECMAScript keywords and reserved literals.
    "await",
    "break",
    "case",
    "catch",
    "class",
    "const",
    "continue",
    "debugger",
    "default",
    "delete",
    "do",
    "else",
    "export",
    "extends",
    "false",
    "finally",
    "for",
    "function",
    "if",
    "import",
    "in",
    "instanceof",
    "new",
    "null",
    "return",
    "super",
    "switch",
    "this",
    "throw",
    "true",
    "try",
    "typeof",
    "var",
    "void",
    "while",
    "with",
    // Future reserved words, including the strict-mode-only ones.
    "enum",
    "implements",
    "interface",
    "let",
    "package",
    "private",
    "protected",
    "public",
    "static",
    "yield",
    // Not bindable in strict mode.
    "arguments",
    "eval",
];

/// Returns whether `name` can be emitted as a raw JavaScript identifier in the
/// generated loader module (an ES module, i.e. strict mode).
fn is_bindable_ident(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if first != '_' && first != '$' && !unicode_id_start::is_id_start(first) {
        return false;
    }
    if !chars.all(|c| {
        c == '_'
            || c == '$'
            // ZWNJ and ZWJ are valid identifier parts per the ECMAScript
            // spec but are not part of ID_Continue.
            || c == '\u{200c}'
            || c == '\u{200d}'
            || unicode_id_start::is_id_continue(c)
    }) {
        return false;
    }
    !RESERVED_WORDS.contains(&name)
}

/// Validates that WebAssembly import and export names are safe to emit as raw
/// JavaScript identifiers in the generated loader module.
///
/// The loader is generated by interpolating these names into `import {}`,
/// destructuring, and `export {}` clauses. WebAssembly names are arbitrary
/// UTF-8 strings, so a crafted `.wasm` binary could otherwise inject arbitrary
/// JavaScript into the generated module.
fn validate_bindable_names(
    imports: &BTreeMap<String, Vec<String>>,
    exports: &[String],
) -> Result<()> {
    for (module, items) in imports {
        for item in items {
            if !is_bindable_ident(item) {
                bail!(
                    "WebAssembly import name {item:?} (imported from module {module:?}) is not a \
                     valid JavaScript identifier and cannot be emitted in the generated loader"
                );
            }
        }
    }
    for export in exports {
        if !is_bindable_ident(export) {
            bail!(
                "WebAssembly export name {export:?} is not a valid JavaScript identifier and \
                 cannot be emitted in the generated loader"
            );
        }
    }
    Ok(())
}

/// Create a javascript loader to instantiate the WebAssembly module with the
/// necessary imports and exports to be processed by [turbopack_ecmascript].
#[turbo_tasks::function]
pub(crate) async fn instantiating_loader_source(
    source: Vc<WebAssemblySource>,
    is_edge: bool,
) -> Result<Vc<Box<dyn Source>>> {
    let analysis = analyze(source).await?;

    // Import and export names are interpolated into the generated module as
    // raw identifiers below. Reject any name that isn't a bindable identifier
    // so a crafted .wasm binary can't inject JavaScript into the bundle.
    validate_bindable_names(&analysis.imports, &analysis.exports)?;

    let mut code = String::new();

    let mut imports_obj = "{".to_string();
    for (path, items) in &analysis.imports {
        writeln!(
            code,
            "import {{ {} }} from {};",
            items.join(", "),
            StringifyJs(path)
        )?;

        writeln!(imports_obj, "\n    {}: {{", StringifyJs(path))?;
        for item in items {
            writeln!(imports_obj, "        {}: {},", StringifyJs(item), item)?;
        }
        writeln!(imports_obj, "    }},")?;
    }
    writeln!(imports_obj, "}}")?;

    writeln!(code, "import {{ instantiate }} from \"WASM_HELPER\";")?;
    writeln!(code, "import wasmPath from \"WASM_PATH\";")?;

    writeln!(code)?;

    // Omitted entirely when `is_edge` is false. As the node and browser
    // implementations do not use this parameter.
    let edge_arg = if is_edge {
        format!(", () => {}", wasm_edge_var_name(Vc::upcast(source)).await?)
    } else {
        String::new()
    };

    writedoc!(
        code,
        r#"
            const {{ {exports} }} = await instantiate(wasmPath, {imports}{edge_arg});

            export {{ {exports} }};
        "#,
        imports = imports_obj,
        edge_arg = edge_arg,
        exports = analysis.exports.join(", "),
    )?;

    let code: RcStr = code.into();

    Ok(Vc::upcast(VirtualSource::new(
        source.ident().await?.path.append("_.loader.mjs")?,
        AssetContent::file(FileContent::Content(File::from(code)).cell()),
    )))
}

/// Create a javascript loader to compile the WebAssembly module and export it
/// without instantiating.
#[turbo_tasks::function]
pub(crate) async fn compiling_loader_source(
    source: Vc<WebAssemblySource>,
    is_edge: bool,
) -> Result<Vc<Box<dyn Source>>> {
    // Omitted entirely when `is_edge` is false. As the node and browser
    // implementations do not use this parameter.
    let edge_arg = if is_edge {
        format!(", () => {}", wasm_edge_var_name(Vc::upcast(source)).await?)
    } else {
        String::new()
    };

    let code: RcStr = formatdoc! {
        r#"
            import {{ compileModule }} from "WASM_HELPER";
            import wasmPath from "WASM_PATH";

            const mod = await compileModule(wasmPath{edge_arg});

            export default mod;
        "#,
        edge_arg = edge_arg,
    }
    .into();

    Ok(Vc::upcast(VirtualSource::new(
        source.ident().await?.path.append("_.loader.mjs")?,
        AssetContent::file(FileContent::Content(File::from(code)).cell()),
    )))
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::*;

    /// Parses a wasm binary the same way `analyze` does and returns the
    /// (imports, exports) name sets.
    fn parse_names(bytes: &[u8]) -> (BTreeMap<String, Vec<String>>, Vec<String>) {
        use wasmparser::{Parser, Payload};

        let mut imports: BTreeMap<String, Vec<String>> = BTreeMap::new();
        let mut exports = Vec::new();
        for payload in Parser::new(0).parse_all(bytes) {
            match payload.unwrap() {
                Payload::ImportSection(s) => {
                    for import in s {
                        let import = import.unwrap();
                        imports
                            .entry(import.module.to_string())
                            .or_default()
                            .push(import.name.to_string());
                    }
                }
                Payload::ExportSection(s) => {
                    for export in s {
                        exports.push(export.unwrap().name.to_string());
                    }
                }
                _ => {}
            }
        }
        (imports, exports)
    }

    #[test]
    fn accepts_common_identifiers() {
        for name in [
            "memory",
            "_start",
            "fd_write",
            "$wasmExport",
            "a",
            "café",
            "関数",
            // ID_Start/ID_Continue but not XID_Start/XID_Continue; ECMAScript
            // (and SWC) accepts these as identifier chars.
            "\u{37a}abc",
            "a\u{e33}",
            "\u{309b}",
        ] {
            assert!(is_bindable_ident(name), "expected {name:?} to be accepted");
        }
        let (imports, exports) = parse_names(
            &wat::parse_str(
                r#"(module
                     (import "wasi_snapshot_preview1" "fd_write" (func))
                     (func (export "_start"))
                     (memory (export "memory") 1))"#,
            )
            .unwrap(),
        );
        validate_bindable_names(&imports, &exports).unwrap();
    }

    #[test]
    fn rejects_non_identifiers() {
        for name in [
            "",
            "0abc",
            "foo-bar",
            "foo bar",
            "a } = x; globalThis.pwned = true; const { b",
            "foo\"; malicious(); //",
        ] {
            assert!(!is_bindable_ident(name), "expected {name:?} to be rejected");
        }
    }

    #[test]
    fn rejects_reserved_words() {
        for name in [
            "class",
            "function",
            "await",
            "enum",
            "yield",
            "eval",
            "arguments",
        ] {
            assert!(!is_bindable_ident(name), "expected {name:?} to be rejected");
        }
    }

    #[test]
    fn rejects_malicious_export_name_from_binary() {
        // A crafted .wasm binary whose export name escapes the generated
        // `const { <exports> } = ...` destructuring must fail validation.
        let (imports, exports) = parse_names(
            &wat::parse_str(
                r#"(module (func (export "a } = x; globalThis.pwned = true; const { b")))"#,
            )
            .unwrap(),
        );
        assert!(
            validate_bindable_names(&imports, &exports).is_err(),
            "expected malicious export name to be rejected"
        );
    }

    #[test]
    fn rejects_malicious_import_name_from_binary() {
        let (imports, exports) = parse_names(
            &wat::parse_str(r#"(module (import "env" "a, b: malicious(), c" (func)))"#).unwrap(),
        );
        assert!(
            validate_bindable_names(&imports, &exports).is_err(),
            "expected malicious import name to be rejected"
        );
    }
}
